#!/usr/bin/env python3
"""Extract the tone tables from the firmware ROM into c_clean/tone_tables.c.

All values are copied byte-for-byte from the ROM; the comments show the
frequency each entry produces (computed from the 4.032 MHz timer clock)."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import srec

F2 = 8.064e6 / 2
CTCSS_STD = [67.0, 71.9, 74.4, 77.0, 79.7, 82.5, 85.4, 88.5, 91.5, 94.8, 97.4, 100.0, 103.5, 107.2,
             110.9, 114.8, 118.8, 123.0, 127.3, 131.8, 136.5, 141.3, 146.2, 151.4, 156.7, 162.2,
             167.9, 173.8, 179.9, 186.2, 192.8, 203.5, 210.7, 218.1, 225.7, 233.6, 241.8, 250.3,
             69.3, 159.8, 165.5, 171.3, 177.3, 183.5, 189.9, 196.6, 199.5, 206.5, 229.1, 254.1]

def main(hexfile, out):
    m = srec.load(hexfile)
    b = lambda a: m[a]
    w = lambda a: m[a] | m[a + 1] << 8
    L = []
    L.append('/* tone_tables.c - generated by tools/gen_tables.py from %s.' % os.path.basename(hexfile))
    L.append(' * Every value is copied unchanged from the ROM; addresses are given for each table. */')
    L.append('#include "tone_tables.h"\n')

    def arr(name, typ, vals, per=16, fmt='0x%02X'):
        L.append('const %s %s[%d] = {' % (typ, name, len(vals)))
        for k in range(0, len(vals), per):
            L.append('    ' + ', '.join(fmt % v for v in vals[k:k + per]) + ',')
        L.append('};\n')

    L.append('/* ROM 0x0021EF: CTCSS sine, 8-bit PWM duty for TA2 (P54) */')
    arr('ctcss_sine', 'uint8_t', [b(0x21EF + i) for i in range(256)])
    L.append('/* ROM 0x0022EF / 0x002353 / 0x002385: per tone 1..50 (index 0 = tone 1)')
    L.append(' *   tx_div : TB0 reload -> DDS sample rate = 4.032 MHz / (tx_div + 1)')
    L.append(' *   tx_inc : DDS phase increment (8-bit phase accumulator)')
    L.append(' *   rx_div : TA4 reload -> correlator sample rate = 4 x tone frequency */')
    L.append('const ctcss_entry_t ctcss_table[CTCSS_TONES] = {')
    for i in range(50):
        tb = w(0x22EF + 2 * i); inc = b(0x2353 + i); rx = w(0x2385 + 2 * i)
        ftx = F2 / (tb + 1) * inc / 256; frx = F2 / (rx + 1) / 4
        L.append('    { %5d, %3d, %5d },  /* %2d: %6.1f Hz  (TX %.2f, RX %.2f) */' % (tb, inc, rx, i + 1, CTCSS_STD[i], ftx, frx))
    L.append('};\n')

    L.append('/* ROM 0x002443: DTMF, 12 keys: 1 2 3 4 5 6 7 8 9 * 0 #')
    L.append(' *   sample rate = 4.032 MHz / (tb1_div + 1), two 8-bit phase increments */')
    keys = '123456789*0#'
    L.append('const dtmf_entry_t dtmf_table[12] = {')
    for k in range(12):
        a = 0x2443 + 4 * k; tb = w(a); i1 = b(a + 2); i2 = b(a + 3); fs = F2 / (tb + 1)
        L.append("    { %4d, %3d, %3d },  /* '%s': %6.1f + %6.1f Hz */" % (tb, i1, i2, keys[k], fs * i1 / 256, fs * i2 / 256))
    L.append('};\n')
    L.append('/* ROM 0x002473 / 0x002673: DTMF low/high group sine (TA1 one-shot widths, summed) */')
    arr('dtmf_sine_low', 'uint16_t', [w(0x2473 + 2 * i) for i in range(256)], 12, '%3d')
    arr('dtmf_sine_high', 'uint16_t', [w(0x2673 + 2 * i) for i in range(256)], 12, '%3d')

    L.append('/* ROM 0x0028FA: selective-call sine (TA1 one-shot width) */')
    arr('selcall_sine', 'uint16_t', [w(0x28FA + 2 * i) for i in range(256)], 12, '%3d')
    digits = '0123456789ABCDE'
    L.append('/* Selective call standards: TB1 reload table + phase increment table, 15 tones each')
    L.append(' * (digits 0-9, A..D, E = repeat).  Tone duration is loaded into TA4 as ms x 126. */')
    L.append('const selcall_std_t selcall_std[3] = {')
    for name, ms, tb_a, inc_a in (('CCIR', 100, 0x2873, 0x2891), ('ZVEI1', 70, 0x28A0, 0x28BE), ('EEA', 40, 0x28CD, 0x28EB)):
        L.append('    { "%s", %d, /* ROM 0x%06X / 0x%06X */' % (name, ms, tb_a, inc_a))
        L.append('      { ' + ', '.join('%d' % w(tb_a + 2 * i) for i in range(15)) + ' },')
        L.append('      { ' + ', '.join('%d' % b(inc_a + i) for i in range(15)) + ' } },')
        L.append('      /* ' + '  '.join('%s=%.0f' % (digits[i], F2 / (w(tb_a + 2 * i) + 1) * b(inc_a + i) / 256) for i in range(15)) + ' */')
    L.append('};')
    open(out, 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
