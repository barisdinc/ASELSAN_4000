#!/usr/bin/env python3
"""Embed the firmware HEX files into firmware.js so index.html works from file://
usage: python3 mkfirmware.py [--surum surum.json] ../../YA4000S.HEX ../../YA4000D.HEX ... > firmware.js"""
import sys, os, json, time
args, surum = sys.argv[1:], {}
if args[:1] == ['--surum']:
    cfg = json.load(open(args[1], encoding='utf-8'))
    surum = {n: '%s V%d-%d' % (cfg['on_ek'], r['major'], r['minor']) for n, r in cfg.get('kayitlar', {}).items()}
    args = args[2:]
out, times = {}, {}
for p in args:
    out[os.path.basename(p)] = open(p).read()
    # build time of the custom images (shown in the pull-downs: which build is this?)
    if 'ozel_firmware' in os.path.abspath(p):
        n = os.path.basename(p)
        times[n] = ((surum[n] + '  ·  ') if n in surum else '') + time.strftime('%d.%m.%Y %H:%M', time.localtime(os.path.getmtime(p)))
print('/* generated by mkfirmware.py - firmware images for the simulator */')
print('window.FIRMWARE_HEX = ' + json.dumps(out) + ';')
print('window.FIRMWARE_TIME = ' + json.dumps(times) + ';')
