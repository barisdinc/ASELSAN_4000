#!/usr/bin/env python3
"""Embed the firmware HEX files into firmware.js so index.html works from file://
usage: python3 mkfirmware.py ../../YA4000S.HEX ../../YA4000D.HEX ... > firmware.js"""
import sys, os, json, time
out, times = {}, {}
for p in sys.argv[1:]:
    out[os.path.basename(p)] = open(p).read()
    # build time of the custom images (shown in the pull-downs: which build is this?)
    if 'ozel_firmware' in os.path.abspath(p):
        times[os.path.basename(p)] = time.strftime('%d.%m.%Y %H:%M', time.localtime(os.path.getmtime(p)))
print('/* generated by mkfirmware.py - firmware images for the simulator */')
print('window.FIRMWARE_HEX = ' + json.dumps(out) + ';')
print('window.FIRMWARE_TIME = ' + json.dumps(times) + ';')
